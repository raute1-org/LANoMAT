#!/usr/bin/env node
// Fail the build on broken internal links in the docs pages and the nav config.
//
// Checks:
//   - Markdown links `[text](target)` and raw `href="target"`
//   - root-absolute links (`/start/quickstart`, `/docs/system/...`)
//   - relative links between pages (`../overview`, `./tools`)
//   - images under /screens/... against public/screens/
//   - nav `to:` links and `file:` docs in zudoku.config.tsx
//
// External URLs, mailto:, smb:, anchors and the generated /api reference are skipped.

import { readdir, readFile, stat } from "node:fs/promises";
import { dirname, extname, join, normalize, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, "..");
const pagesRoot = join(siteRoot, "pages");
const publicRoot = join(siteRoot, "public");

const walk = async (dir, suffix) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path, suffix)));
    else if (suffix.some((s) => entry.name.endsWith(s))) files.push(path);
  }
  return files;
};

const pageFiles = (await walk(pagesRoot, [".md", ".mdx"])).sort();
const publicFiles = await walk(publicRoot, [".png", ".svg", ".ico", ".jpg", ".webp", ".json"]);

const toPosix = (p) => p.split("\\").join("/");

/** pages/start/introduction.mdx -> /start/introduction */
const routeFor = (file) => {
  const rel = toPosix(relative(pagesRoot, file)).replace(/\.(md|mdx)$/, "");
  const route = "/" + rel.replace(/(^|\/)index$/, "");
  return route === "/" ? "/" : route.replace(/\/$/, "");
};

const routes = new Map(pageFiles.map((file) => [routeFor(file), file]));
const publicSet = new Set(publicFiles.map((file) => "/" + toPosix(relative(publicRoot, file))));

const stripCode = (text) =>
  text
    .replace(/```[\s\S]*?```/g, "")
    .replace(/~~~[\s\S]*?~~~/g, "")
    .replace(/`[^`\n]*`/g, "");

const failures = [];

const checkTarget = (raw, source, line) => {
  let target = raw.trim();
  if (!target) return;
  if (target.startsWith("<") && target.endsWith(">")) target = target.slice(1, -1);
  // Drop a title: [x](/path "title")
  target = target.split(/\s+/)[0];
  if (!target) return;

  if (/^(https?:|mailto:|tel:|smb:|magnet:|#)/i.test(target)) return;
  if (target.startsWith("//")) return;

  const [pathPart, hash] = target.split("#");
  if (!pathPart) return; // pure anchor

  let decoded = pathPart;
  try {
    decoded = decodeURI(pathPart);
  } catch {
    // keep raw
  }

  // The API reference is generated by Zudoku from apis/lanomat.openapi.yaml.
  if (decoded === "/api" || decoded.startsWith("/api/")) return;

  // BasePath-aware authoring: /docs/... is the deployed URL of /...
  let route = decoded;
  if (route === "/docs") route = "/";
  else if (route.startsWith("/docs/")) route = route.slice("/docs".length);

  // Static assets live in public/ and are served below basePath.
  if (extname(route)) {
    if (route.startsWith("/screens/") || route.startsWith("/logo") || route.startsWith("/favicon") || route.startsWith("/apple-touch")) {
      if (!publicSet.has(route)) {
        failures.push(`${toPosix(relative(siteRoot, source))}:${line}: missing public asset ${route}`);
      }
      return;
    }
  }

  if (route.startsWith("/")) {
    if (!routes.has(route.replace(/\/$/, "") || "/")) {
      failures.push(`${toPosix(relative(siteRoot, source))}:${line}: no page for ${target}`);
    }
    return;
  }

  // Relative page link: resolve against the source file's directory.
  const baseDir = dirname(source);
  const resolved = normalize(join(baseDir, route));
  const candidates = [resolved, `${resolved}.md`, `${resolved}.mdx`, join(resolved, "index.md"), join(resolved, "index.mdx")];
  const exists = candidates.some((candidate) => [...routes.values()].includes(candidate));
  if (!exists) {
    failures.push(`${toPosix(relative(siteRoot, source))}:${line}: no page for relative link ${target}`);
  }
};

for (const file of pageFiles) {
  const text = stripCode(await readFile(file, "utf8"));
  const lines = text.split("\n");
  lines.forEach((line, index) => {
    const lineNo = index + 1;
    // Markdown links and images
    for (const match of line.matchAll(/!?\[[^\]]*\]\(([^)]+)\)/g)) {
      checkTarget(match[1], file, lineNo);
    }
    // Raw HTML href/src
    for (const match of line.matchAll(/(?:href|src)="([^"]+)"/g)) {
      checkTarget(match[1], file, lineNo);
    }
  });
}

// Navigation config: only quoted static values.
const configPath = join(siteRoot, "zudoku.config.tsx");
const config = await readFile(configPath, "utf8");
const configLines = config.split("\n");
configLines.forEach((line, index) => {
  for (const match of line.matchAll(/\bto:\s*"([^"]+)"/g)) {
    const target = match[1];
    if (target.startsWith("http")) continue;
    if (target === "/api" || target.startsWith("/api/")) continue;
    if (!routes.has(target.replace(/\/$/, "") || "/")) {
      failures.push(`zudoku.config.tsx:${index + 1}: nav link ${target} has no page`);
    }
  }
  for (const match of line.matchAll(/\bfile:\s*"([^"]+)"/g)) {
    const file = match[1];
    const candidates = [
      join(pagesRoot, `${file}.md`),
      join(pagesRoot, `${file}.mdx`),
      join(pagesRoot, file),
    ];
    const found = candidates.some((candidate) => [...routes.values()].includes(candidate));
    if (!found) {
      failures.push(`zudoku.config.tsx:${index + 1}: nav doc ${file} has no page`);
    }
  }
});

if (failures.length > 0) {
  console.error(`Broken internal links (${failures.length}):`);
  for (const failure of failures) console.error(`  ${failure}`);
  process.exit(1);
}

console.log(
  `Checked ${pageFiles.length} pages, ${publicFiles.length} public assets and the navigation: no broken internal links.`,
);
